async function buildDependencyMap(): Promise<string> {
  const areas = ["pages", "features", "components", "hooks"];
  const lines: string[] = ["# Cross-Area Import Dependencies\n"];

  for (const area of areas) {
    const areaDir = repoPath("src", area);
    const topDirs = await listDir(areaDir);

    for (const topDir of topDirs) {
      const full = join(areaDir, topDir);
      if (!(await isDirectory(full))) continue;

      let content = "";
      const entries = await listDir(full);
      for (const e of entries) {
        if (e.endsWith(".tsx") || e.endsWith(".ts")) {
          try { content = await readTextFile(join(full, e)); break; } catch { /**/ }
        }
      }
      if (!content) continue;

      const imports = content.matchAll(/from ['"]\.\.\/(\w+)/g);
      const external = new Set<string>();
      for (const m of imports) {
        if (areas.includes(m[1]) && m[1] !== area) external.add(m[1]);
      }

      if (external.size > 0) {
        lines.push(`  src/${area}/${topDir} → imports from: ${[...external].join(", ")}`);
      }
    }
  }

  if (lines.length === 1) lines.push("  (No cross-area imports detected in sampled files)");
  return lines.join("\n");
}

export async function getArchitecture(input: GetArchitectureInput): Promise<string> {
  const sections: string[] = [];
  const s = input.section;
  if (s === "all" || s === "overview") sections.push(getOverview());
  if (s === "all" || s === "patterns") sections.push(getPatterns());
  if (s === "all" || s === "tech_stack") sections.push(getTechStack());
  if (s === "all" || s === "dependencies") sections.push(await buildDependencyMap());
  return sections.join("\n\n---\n\n");
}
