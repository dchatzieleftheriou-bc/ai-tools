import { z } from "zod";
import { repoPath, listDir, isDirectory, readTextFile } from "../repo.js";
import { join } from "path";

export const getArchitectureSchema = z.object({
  section: z.enum(["overview", "patterns", "tech_stack", "dependencies", "all"]).optional().default("all"),
});

export type GetArchitectureInput = z.infer<typeof getArchitectureSchema>;

function getOverview(): string {
  return `# Web Wallet Architecture Overview

## Stack
- **Next.js** (Pages Router) with TypeScript
- **React** with hooks and context for state management
- No Redux — state is managed via React Context + custom hooks

## Project Layout (src/)
- \`pages/\` — Next.js pages + API routes (file-based routing)
- \`features/\` — Feature-specific logic modules
- \`components/\` — Reusable React components, organized by domain
- \`hooks/\` — Shared custom React hooks
- \`contexts/\` — React context providers for global state
- \`models/\` — Shared TypeScript interfaces and types
- \`generated/openapi/\` — Orval-generated type-safe API fetchers (from OpenAPI specs)
- \`utils/\` — Utility functions
- \`openapi/\` (root) — OpenAPI spec files used to generate API types

## Data Flow
1. **Pages** are entry points — they compose components and provide contexts
2. **Components** render UI and call hooks for data and actions
3. **Custom hooks** orchestrate API calls and local state
4. **API layer** uses Orval-generated fetchers for type-safe HTTP calls
5. **Firebase Remote Config** controls feature flags at runtime

## Key Integration Points
- **Authentication**: contexts provide auth state; \`pages/auth/\` handles login flows
- **i18n**: \`react-intl\` + \`global.translations.ts\` for all user-facing strings
- **API types**: Generated by Orval from \`openapi/*.yaml\` → \`src/generated/openapi/\`
- **Middleware**: \`src/middleware.ts\` intercepts requests for auth and redirects
`;
}

function getPatterns(): string {
  return `# Key Patterns

## 1. React Context + Custom Hooks (State Management)
- No Redux. State is shared via React Context (\`createContext\`, \`useContext\`)
- Contexts live in \`src/contexts/\` or co-located with features
- Custom hooks abstract data fetching and state logic from components
- Typical hook shape: returns \`{ data, loading, error }\` + action callbacks

## 2. Orval API Layer
- All backend APIs are described in OpenAPI specs in \`openapi/\`
- Orval generates type-safe axios fetchers into \`src/generated/openapi/\`
- Components/hooks import generated fetchers directly — no manual HTTP calls
- Custom axios instance in \`src/utils/orval/\` adds auth headers + error handling

## 3. Feature Flag Pattern (Firebase Remote Config)
- Firebase Remote Config provides boolean/string flags
- Flags are read via custom hooks that wrap the Firebase SDK
- Feature-gated components check flags before rendering

## 4. i18n (react-intl)
- All user-visible strings live as keys in \`src/global.translations.ts\`
- Components use \`useIntl()\` hook or \`<FormattedMessage>\` component
- Translation files per locale in \`src/languages/\`

## 5. Next.js Routing
- File-based routing via \`src/pages/\`
- \`src/middleware.ts\` runs on matched routes for auth guards
- Dynamic routes use \`[param]\` and \`[...slug]\` file naming
- API routes under \`src/pages/api/\` expose Next.js serverless functions
`;
}

